export function getFilteredListings(
  listings: Listing[],
  searchQuery: string,
  filters: {
    categories: string[];
    states: string[];
    minPrice: number;
    maxPrice: number;
    location: string;
    evaluationType: string;
    featuredOnly: boolean;
  },
  sortBy: string = "newest"
): Listing[] {
  let filtered = listings.filter((listing) => {
    // Search
    const searchLower = searchQuery.toLowerCase();
    const matchesSearch =
      listing.title.toLowerCase().includes(searchLower) ||
      listing.description.toLowerCase().includes(searchLower);
    if (searchQuery && !matchesSearch) return false;

    // Category
    if (filters.categories.length > 0 && !filters.categories.includes(listing.category)) {
      return false;
    }

    // State
    if (filters.states.length > 0 && !filters.states.includes(listing.state)) {
      return false;
    }

    // Price Range
    if (listing.asking_price < filters.minPrice || listing.asking_price > filters.maxPrice) {
      return false;
    }

    // Location
    if (filters.location && listing.location !== filters.location) {
      return false;
    }

    // Evaluation Type
    if (filters.evaluationType && listing.evaluation_type !== filters.evaluationType) {
      return false;
    }

    // Featured
    if (filters.featuredOnly && !listing.is_featured) {
      return false;
    }

    return true;
  });

  // Sort
  switch (sortBy) {
    case "price_asc":
      return filtered.sort((a, b) => a.asking_price - b.asking_price);
    case "price_desc":
      return filtered.sort((a, b) => b.asking_price - a.asking_price);
    case "most_viewed":
      return filtered.sort((a, b) => b.view_count - a.view_count);
    case "newest":
    default:
      return filtered.sort(() => Math.random() - 0.5); // Shuffle for demo
  }
}
